import fs from "fs";
import path from "path";

/**
 * Keeps `test/fixtures/fixtures.ts` (the import list of every
 * `*.fixture.tsx`, which replaced Vite's `import.meta.glob`) in sync with the
 * fixture files on disk. The file is committed so `bun run ts` sees it; the
 * test preload rewrites it when a fixture was added or removed.
 */

const FIXTURES_DIR = path.resolve(import.meta.dir, "../fixtures");
export const FIXTURE_LIST_FILE = path.join(FIXTURES_DIR, "fixtures.ts");

/** Source of `test/fixtures/fixtures.ts` for the fixture files on disk. */
export function fixtureListSource(): string {
  const files = [...new Bun.Glob("**/*.fixture.tsx").scanSync(FIXTURES_DIR)]
    .map((file) => file.split(path.sep).join("/"))
    .sort();

  return [
    "// Generated by test/harness/fixture-list.ts (the test preload keeps it in",
    "// sync): every fixture file, each of which registers itself when imported.",
    ...files.map((file) => `import "./${file.replace(/\.tsx$/, ".js")}";`),
    "",
  ].join("\n");
}

/** Rewrites the fixture list when it differs from the files on disk. */
export function syncFixtureList(): void {
  const source = fixtureListSource();
  const current = fs.existsSync(FIXTURE_LIST_FILE)
    ? fs.readFileSync(FIXTURE_LIST_FILE, "utf8")
    : "";
  if (current !== source) fs.writeFileSync(FIXTURE_LIST_FILE, source);
}
